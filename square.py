def area(a):
    """
    Вычисляет площадь квадрата.
    Аргументы:
        a (int): сторона квадрата.
    Возвращает:
        int: площадь квадрата.
    Пример вызова:
        area(4)
        16
    """
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата.
    Аргументы:
        a (int): сторона квадрата.
    Возвращает:
        int: периметр квадрата.
    Пример вызова:
        perimeter(4)
        16
    """
    return 4 * a
