def area(a, h):
    """
    Вычисляет площадь треугольника по основанию и высоте.
    Аргументы:
        a (int): основание треугольника.
        h (int): высота, проведённая к основанию.
    Возвращает:
        int: площадь треугольника.
    Пример вызова:
        area(6, 4)
        12
    """
    return a * h / 2


def perimeter(a, b, c):
    """
    Вычисляет периметр треугольника.
    Аргументы:
        a (int): первая сторона.
        b (int): вторая сторона.
        c (int): третья сторона.
    Возвращает:
        int: периметр треугольника.
    Пример вызова:
        perimeter(3, 4, 5)
        12
    """
    return a + b + c
